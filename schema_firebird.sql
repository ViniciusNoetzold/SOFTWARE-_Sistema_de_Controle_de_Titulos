-- 1. TABELA DE USUÁRIOS E PERMISSÕES DO SISTEMA
CREATE TABLE USUARIOS (
  ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NOME VARCHAR(100) NOT NULL,
  EMAIL VARCHAR(150) NOT NULL UNIQUE,
  USERNAME VARCHAR(50) NOT NULL UNIQUE,
  SENHA_HASH VARCHAR(255) NOT NULL,
  PERFIL VARCHAR(20) DEFAULT 'OPERADOR', -- ADMIN / OPERADOR / FINANCEIRO
  ATIVO SMALLINT DEFAULT 1,
  AVATAR_URL VARCHAR(500),
  CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  ULTIMO_ACESSO TIMESTAMP
);

-- 2. TABELA DE CLIENTES E FORNECEDORES (ENTIDADES)
CREATE TABLE ENTIDADES (
  ID VARCHAR(50) PRIMARY KEY,
  NOME VARCHAR(150) NOT NULL,
  DOCUMENTO VARCHAR(25) NOT NULL, -- CPF/CNPJ
  TIPO_ENTIDADE VARCHAR(20) NOT NULL, -- CLIENTE / FORNECEDOR / AMBOS
  TELEFONE VARCHAR(30),
  EMAIL VARCHAR(150),
  ENDERECO VARCHAR(255),
  LIMITE_CREDITO DECIMAL(18,2) DEFAULT 0.00,
  STATUS VARCHAR(20) DEFAULT 'ATIVO',
  CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 3. TABELA DE TÍTULOS (CONTAS A RECEBER E PAGAR)
CREATE TABLE TITULOS (
  ID VARCHAR(50) PRIMARY KEY,
  ID_ENTIDADE VARCHAR(50) REFERENCES ENTIDADES(ID),
  TIPO_TITULO VARCHAR(20) NOT NULL, -- RECEBER / PAGAR
  NUMERO_DOCUMENTO VARCHAR(50) NOT NULL,
  VALOR_ORIGINAL DECIMAL(18,2) NOT NULL,
  VALOR_PAGO DECIMAL(18,2) DEFAULT 0.00,
  SALDO_DEVEDOR DECIMAL(18,2) NOT NULL,
  DATA_EMISSAO DATE DEFAULT CURRENT_DATE,
  DATA_VENCIMENTO DATE NOT NULL,
  DATA_PAGAMENTO DATE,
  STATUS VARCHAR(20) DEFAULT 'EM_ABERTO', -- EM_ABERTO / PAGO / CANCELADO
  CENTRO_CUSTO VARCHAR(100) DEFAULT 'Geral',
  OBSERVACOES VARCHAR(500),
  CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 4. TABELA DE CHEQUES COM RASTREAMENTO E AUDITORIA POR USUÁRIO
CREATE TABLE CHEQUES (
  ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  TITULAR VARCHAR(150) NOT NULL,
  NUMERO_CHEQUE VARCHAR(30) NOT NULL,
  BANCO VARCHAR(100) DEFAULT 'Itaú (341)',
  AGENCIA VARCHAR(20) DEFAULT '0001',
  CONTA VARCHAR(30) DEFAULT '00000-0',
  VALOR DECIMAL(18,2) NOT NULL,
  TIPO VARCHAR(20) DEFAULT 'RECEBIDO', -- RECEBIDO / EMITIDO
  STATUS VARCHAR(20) DEFAULT 'EM ABERTO', -- EM ABERTO / COMPENSADO / DEVOLVIDO
  DATA_EMISSAO DATE DEFAULT CURRENT_DATE,
  DATA_VENCIMENTO DATE NOT NULL,
  
  -- Campos de Auditoria por Usuário
  CRIADO_POR INTEGER REFERENCES USUARIOS(ID),
  ATUALIZADO_POR INTEGER REFERENCES USUARIOS(ID),
  CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 5. ÍNDICES DE ALTO DESEMPENHO PARA REDE
CREATE INDEX IDX_USUARIOS_USERNAME ON USUARIOS(USERNAME);
CREATE INDEX IDX_USUARIOS_EMAIL ON USUARIOS(EMAIL);
CREATE INDEX IDX_TITULOS_VENCIMENTO ON TITULOS(DATA_VENCIMENTO);
CREATE INDEX IDX_TITULOS_ENTIDADE ON TITULOS(ID_ENTIDADE);
CREATE INDEX IDX_TITULOS_STATUS ON TITULOS(STATUS);
CREATE INDEX IDX_CHEQUES_VENCIMENTO ON CHEQUES(DATA_VENCIMENTO);
CREATE INDEX IDX_CHEQUES_STATUS ON CHEQUES(STATUS);
CREATE INDEX IDX_CHEQUES_CRIADO_POR ON CHEQUES(CRIADO_POR);

