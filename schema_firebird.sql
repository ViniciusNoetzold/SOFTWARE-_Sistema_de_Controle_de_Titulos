-- 1. TABELA DE USUÁRIOS E PERMISSÕES DE ACESSO
CREATE TABLE USUARIOS (
  ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NOME VARCHAR(100) NOT NULL,
  EMAIL VARCHAR(150) NOT NULL UNIQUE,
  USERNAME VARCHAR(50) NOT NULL UNIQUE,
  SENHA_HASH VARCHAR(255) NOT NULL,
  PERFIL VARCHAR(20) DEFAULT 'OPERADOR',
  ATIVO SMALLINT DEFAULT 1,
  AVATAR_URL VARCHAR(500),
  CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  ULTIMO_ACESSO TIMESTAMP
);

-- 2. TABELA DE CHEQUES COM RASTREAMENTO E AUDITORIA POR USUÁRIO
CREATE TABLE CHEQUES (
  ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  TITULAR VARCHAR(150) NOT NULL,
  NUMERO_CHEQUE VARCHAR(30) NOT NULL,
  BANCO VARCHAR(100) DEFAULT 'Itaú (341)',
  AGENCIA VARCHAR(20) DEFAULT '0001',
  CONTA VARCHAR(30) DEFAULT '00000-0',
  VALOR DECIMAL(18,2) NOT NULL,
  TIPO VARCHAR(20) DEFAULT 'RECEBIDO', -- RECEBIDO / EMITIDO
  STATUS VARCHAR(20) DEFAULT 'EM ABERTO', -- EM ABERTO / COMPENSADO / DEVOLVIDO
  DATA_EMISSAO DATE DEFAULT CURRENT_DATE,
  DATA_VENCIMENTO DATE NOT NULL,
  
  -- Campos de Auditoria por Usuário (Foreign Keys)
  CRIADO_POR INTEGER REFERENCES USUARIOS(ID),
  ATUALIZADO_POR INTEGER REFERENCES USUARIOS(ID),
  CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  ATUALIZADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Índices de Desempenho para Consultas em Rede
CREATE INDEX IDX_USUARIOS_EMAIL ON USUARIOS(EMAIL);
CREATE INDEX IDX_USUARIOS_USERNAME ON USUARIOS(USERNAME);
CREATE INDEX IDX_CHEQUES_VENCIMENTO ON CHEQUES(DATA_VENCIMENTO);
CREATE INDEX IDX_CHEQUES_STATUS ON CHEQUES(STATUS);
CREATE INDEX IDX_CHEQUES_CRIADO_POR ON CHEQUES(CRIADO_POR);

